import { Lock } from "lucide-react";
import Link from "next/link";
import { useTranslations } from "next-intl";
import { type FormEvent, useActionState, useState } from "react";
import type { AccountErrorKey, AddressField, CountryOption } from "@/lib/account/types";
import { clientAddressErrors, readAddressForm } from "@/ui/components/address/address-errors";
import { AddressFields } from "@/ui/components/address/address-fields";
import { SubmitButton } from "@/ui/components/auth/auth-form-parts";
import { enabledProviders } from "../payment/providers";
import type { PlaceOrderAction, PlaceOrderState } from "../types";
import { StepMessage } from "./step-message";

const idle: PlaceOrderState = { status: "idle" };

type FieldErrors = Partial<Record<AddressField, AccountErrorKey>>;

/**
 * Payment (ARCHITECTURE §10.9): the billing address ("same as shipping" unless unticked), the
 * payment provider's UI and the button that places the order. `attemptId` is generated by the
 * server for this render and posted back; the Server Action uses it as the payment's idempotency
 * key, so a double submit or a retry can never charge twice. A new one arrives in the action's
 * state only when the old one is spent.
 */
export function PaymentStep({
  attemptId,
  providerIds,
  countries,
  placeOrder,
}: {
  attemptId: string;
  /** The enabled providers' ids (the registry's UI is looked up here, in the browser bundle). */
  providerIds: string[];
  countries: CountryOption[];
  placeOrder: PlaceOrderAction;
}) {
  const t = useTranslations("checkout.payment");
  const [state, formAction] = useActionState(placeOrder, idle);
  const [same, setSame] = useState(true);
  const [clientErrors, setClientErrors] = useState<FieldErrors | null>(null);
  const provider = enabledProviders(providerIds)[0];

  // A billing form with errors never reaches the Server Action.
  const validate = (event: FormEvent<HTMLFormElement>) => {
    if (same) return;
    const errors = clientAddressErrors(readAddressForm(new FormData(event.currentTarget)));
    setClientErrors(errors);
    if (errors) event.preventDefault();
  };
  const errors: FieldErrors =
    clientErrors ?? (state.status === "error" ? (state.fieldErrors ?? {}) : {});

  return (
    <section aria-labelledby="checkout-payment-title" className="space-y-6">
      <h1 id="checkout-payment-title" className="text-2xl font-semibold">
        {t("title")}
      </h1>
      {provider === undefined ? (
        <p role="alert" className="text-sm text-destructive">
          {t("noProviders")}
        </p>
      ) : (
        <form action={formAction} onSubmit={validate} noValidate className="space-y-6">
          <input type="hidden" name="attemptId" value={state.nextAttemptId ?? attemptId} />
          <input type="hidden" name="providerId" value={provider.id} />

          <fieldset className="space-y-4">
            <legend className="mb-2 text-lg font-semibold">{t("billingTitle")}</legend>
            <label className="flex items-center gap-2 text-sm">
              <input
                type="checkbox"
                name="billingSameAsShipping"
                value="true"
                checked={same}
                onChange={(event) => setSame(event.target.checked)}
              />
              {t("sameAsShipping")}
            </label>
            {same ? null : (
              <div className="space-y-4">
                <AddressFields countries={countries} submitted={state.values} errors={errors} />
              </div>
            )}
          </fieldset>

          <div className="space-y-3">
            <h2 className="text-lg font-semibold">{t("methodTitle")}</h2>
            <provider.Component />
          </div>

          <StepMessage message={state.message} />
          <SubmitButton label={t("placeOrder")} pendingLabel={t("placing")} />
          <p
            role="note"
            className="flex items-center justify-center gap-1.5 text-center text-xs text-muted-foreground"
          >
            <Lock className="h-3.5 w-3.5 shrink-0" aria-hidden="true" />
            {t("secure")}
          </p>
        </form>
      )}
      <p className="text-sm">
        <Link
          href="/checkout?step=shipping"
          className="text-muted-foreground underline underline-offset-2"
        >
          {t("back")}
        </Link>
      </p>
    </section>
  );
}
